// One-off / re-runnable generator: CSV -> data.js consumed by the site (no server/fetch needed).
const fs = require('fs');
const path = require('path');

function parseCsv(file) {
  return fs.readFileSync(path.join(__dirname, file), 'utf8')
    .trim()
    .split('\n')
    .slice(1)
    .map(l => l.trim())
    .filter(Boolean);
}

const matchLines = parseCsv('Stats_joueur.csv');
const matches = matchLines.map(line => {
  const [p1, s1, s2, p2, winner, ht1, ht2] = line.split(',');
  return {
    p1, s1: +s1, s2: +s2, p2, winner,
    ht1: ht1 ? +ht1 : null,
    ht2: ht2 ? +ht2 : null
  };
});

const playerLines = parseCsv('Stats_par_joueur.csv');
const players = playerLines.map(line => {
  const [name, mj, w, d, l, gf, ga, diff, pts, winPct] = line.split(',');
  return {
    name,
    mj: +mj, w: +w, d: +d, l: +l,
    gf: +gf, ga: +ga, diff: +diff, pts: +pts,
    winPct: +winPct
  };
});

const out = `// AUTO-GENERATED by data/build_data.js — re-run \`node data/build_data.js\` after updating the CSVs in data/.
window.BXR_DATA = ${JSON.stringify({ matches, players }, null, 0)};
`;

fs.writeFileSync(path.join(__dirname, '..', 'data.js'), out, 'utf8');
console.log(`data.js written: ${matches.length} matches, ${players.length} joueurs.`);
